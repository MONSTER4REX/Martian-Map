#!/usr/bin/env python
"""Generate the friend-runnable training notebooks from code (keeps them in sync).

Writing .ipynb JSON by hand is error-prone; this emits them so the source of
truth stays Python. Each notebook installs Marswalk from GitHub, trains on a
GPU (or CPU), and writes ``<model>_report.json`` + ``<model>_samples.png`` for
the runner to send back (see ``notebooks/README.md``). Run:

    python scripts/make_ml_notebooks.py
"""

from __future__ import annotations

import json
import pathlib

ROOT = pathlib.Path(__file__).resolve().parent.parent
NB = ROOT / "notebooks"
REPO = "https://github.com/MONSTER4REX/Martian-Map.git"


def md(text: str) -> dict:
    return {"cell_type": "markdown", "metadata": {}, "source": text}


def code(text: str) -> dict:
    return {"cell_type": "code", "execution_count": None, "metadata": {}, "outputs": [],
            "source": text}


def notebook(cells: list[dict]) -> dict:
    return {
        "cells": cells,
        "metadata": {
            "kernelspec": {"display_name": "Python 3", "language": "python", "name": "python3"},
            "language_info": {"name": "python", "version": "3.11"},
            "accelerator": "GPU",
        },
        "nbformat": 4, "nbformat_minor": 5,
    }


def write(path: pathlib.Path, nb: dict) -> None:
    path.write_text(json.dumps(nb, indent=1), encoding="utf-8")
    print("wrote", path.relative_to(ROOT), f"({len(nb['cells'])} cells)")


# --------------------------------------------------------------------------- M7
HEURISTIC = notebook([
    md("# M7 — learned A* heuristic (Marswalk)\n\n"
       "Trains a small network to predict on-foot **cost-to-go to a goal**, using "
       "training data generated by Marswalk's *own* planner (no external dataset). "
       "It's tiny — runs in a few minutes on **any GPU or even CPU**.\n\n"
       "**How to run:** Runtime → GPU (optional), then **Run all**. When it's done, "
       "download **`heuristic_report.json`** and **`heuristic_samples.png`** and send "
       "them back. That's it."),
    code("!pip install -q \"git+" + REPO + "\"\n"
         "import torch\n"
         "dev = 'cuda' if torch.cuda.is_available() else 'cpu'\n"
         "print('torch', torch.__version__, '| device', dev,\n"
         "      '|', torch.cuda.get_device_name(0) if dev=='cuda' else 'CPU')"),
    md("## Build data from the planner, train, and evaluate\n\n"
       "Targets are exact `time_to_haven_field` computations, so nothing here is "
       "fabricated. We report error vs the trivial straight-line lower bound and the "
       "**admissible fraction** (share where prediction ≤ truth — what A* needs)."),
    code("import json, time\n"
         "import numpy as np\n"
         "from marswalk.ml.heuristic import build_dataset, train_mlp, evaluate\n"
         "\n"
         "N_TERRAINS = 120   # raise for a stronger model\n"
         "EPOCHS = 120\n"
         "\n"
         "t0 = time.time()\n"
         "X, y, flat = build_dataset(range(N_TERRAINS), shape=(40, 40), cellsize=10.0)\n"
         "print(f'dataset: {len(X):,} cells from {N_TERRAINS} terrains')\n"
         "model = train_mlp(X, y, epochs=EPOCHS, device=dev)\n"
         "rep = evaluate(model, X, y, flat)\n"
         "secs = time.time() - t0\n"
         "print(rep)"),
    code("report = {**rep.as_dict(), 'device': (torch.cuda.get_device_name(0) if dev=='cuda' else 'CPU'),\n"
         "          'n_terrains': N_TERRAINS, 'epochs': EPOCHS, 'seconds': round(secs, 1),\n"
         "          'final_loss': round(model.history[-1], 5)}\n"
         "with open('heuristic_report.json', 'w') as f:\n"
         "    json.dump(report, f, indent=2)\n"
         "print('wrote heuristic_report.json')\n"
         "print(json.dumps(report, indent=2))"),
    code("import matplotlib\n"
         "matplotlib.use('Agg')\n"
         "import matplotlib.pyplot as plt\n"
         "pred = model.predict(X)\n"
         "fig, ax = plt.subplots(1, 2, figsize=(11, 4.4))\n"
         "idx = np.random.default_rng(0).choice(len(y), size=min(4000, len(y)), replace=False)\n"
         "ax[0].scatter(y[idx]/60, pred[idx]/60, s=4, alpha=.3, color='#e2572b')\n"
         "lim = max(y[idx].max(), pred[idx].max())/60\n"
         "ax[0].plot([0, lim], [0, lim], 'k--', lw=1)\n"
         "ax[0].set_xlabel('true cost-to-go (min)'); ax[0].set_ylabel('predicted (min)')\n"
         "ax[0].set_title(f\"learned heuristic — MAE {rep.mae_s/60:.2f} min, \"\n"
         "                f\"{rep.admissible_fraction*100:.1f}% admissible\")\n"
         "ax[1].plot(np.array(model.history)); ax[1].set_xlabel('epoch'); ax[1].set_ylabel('loss')\n"
         "ax[1].set_title('training loss')\n"
         "fig.tight_layout(); fig.savefig('heuristic_samples.png', dpi=120)\n"
         "print('wrote heuristic_samples.png')"),
    md("## Send back\n\n"
       "Download **`heuristic_report.json`** and **`heuristic_samples.png`** and send "
       "them to the lead, plus your GPU name (printed above). Thanks!"),
])


# --------------------------------------------------------------------------- M6
DTM_ARTIFACTS = notebook([
    md("# M6 — DTM artifact detector (Marswalk)\n\n"
       "Trains a small CNN to flag **DEM/DTM artifacts** — box-steps and CCD-seam "
       "lines — from hillshade. Labels are made by injecting artifacts of known "
       "type into clean synthetic DEMs (honest weak supervision); you then run the "
       "detector over real HiRISE DTM hillshades to flag suspect tiles.\n\n"
       "**How to run:** Runtime → GPU (optional), **Run all**, then send back "
       "**`dtm_artifacts_report.json`** and **`dtm_artifacts_samples.png`**."),
    code("!pip install -q \"git+" + REPO + "\"\n"
         "import torch\n"
         "dev = 'cuda' if torch.cuda.is_available() else 'cpu'\n"
         "print('torch', torch.__version__, '| device', dev,\n"
         "      '|', torch.cuda.get_device_name(0) if dev=='cuda' else 'CPU')"),
    md("## Build labelled patches, train, evaluate on unseen terrain\n\n"
       "Train and test terrains are disjoint, so the score reflects generalization, "
       "not memorized texture."),
    code("import json, time\n"
         "import numpy as np\n"
         "from marswalk.ml.dtm_artifacts import make_dataset, train_cnn, evaluate\n"
         "\n"
         "Xtr, ytr = make_dataset(range(60), per_terrain=16, step_frac=0.25)\n"
         "Xte, yte = make_dataset(range(1000, 1012), per_terrain=16, step_frac=0.25)\n"
         "print(f'train {len(Xtr)} patches | test {len(Xte)} (disjoint terrains)')\n"
         "t0 = time.time()\n"
         "model = train_cnn(Xtr, ytr, epochs=30, device=dev)\n"
         "rep = evaluate(model, Xte, yte)\n"
         "secs = time.time() - t0\n"
         "print(rep)"),
    code("report = {**rep.as_dict(), 'device': (torch.cuda.get_device_name(0) if dev=='cuda' else 'CPU'),\n"
         "          'epochs': 30, 'seconds': round(secs, 1), 'final_loss': round(model.history[-1], 5)}\n"
         "with open('dtm_artifacts_report.json', 'w') as f:\n"
         "    json.dump(report, f, indent=2)\n"
         "print(json.dumps(report, indent=2))"),
    code("import matplotlib\n"
         "matplotlib.use('Agg')\n"
         "import matplotlib.pyplot as plt\n"
         "pred = model.predict(Xte)\n"
         "lab = {0: 'clean', 1: 'artifact'}\n"
         "idx = np.random.default_rng(1).choice(len(Xte), size=8, replace=False)\n"
         "fig, ax = plt.subplots(2, 4, figsize=(11, 6))\n"
         "for a, i in zip(ax.ravel(), idx):\n"
         "    a.imshow(Xte[i, 0], cmap='gray'); a.set_xticks([]); a.set_yticks([])\n"
         "    ok = pred[i] == yte[i]\n"
         "    a.set_title(f\"GT {lab[yte[i]]} / pred {lab[pred[i]]}\",\n"
         "                color=('green' if ok else 'red'), fontsize=9)\n"
         "fig.suptitle(f\"DTM artifact detector — test acc {rep.accuracy*100:.1f}%, F1 {rep.f1:.2f}\")\n"
         "fig.tight_layout(); fig.savefig('dtm_artifacts_samples.png', dpi=120)\n"
         "print('wrote dtm_artifacts_samples.png')"),
    md("## Send back\n\n"
       "Download **`dtm_artifacts_report.json`** and **`dtm_artifacts_samples.png`** "
       "and send them to the lead, plus your GPU name. Thanks!"),
])


# --------------------------------------------------------------------------- M5
THERMAL = notebook([
    md("# M5 — thermal emulator (Marswalk)\n\n"
       "Trains a small MLP surrogate of the surface-temperature model "
       "`physics.thermal.surface_temp_range_k` — fast (T_min, T_max) from "
       "(thermal inertia, insolation, albedo). The underlying model is a C3 "
       "**placeholder**; the emulator's realism is bounded by it — swap in a "
       "validated thermal model and retrain for production.\n\n"
       "**How to run:** **Run all** (CPU is fine), then send back "
       "**`thermal_emulator_report.json`** and **`thermal_emulator_samples.png`**."),
    code("!pip install -q \"git+" + REPO + "\"\n"
         "import torch\n"
         "dev = 'cuda' if torch.cuda.is_available() else 'cpu'\n"
         "print('torch', torch.__version__, '| device', dev)"),
    md("## Build data from the physics model, train, evaluate on a fresh draw"),
    code("import json, time\n"
         "import numpy as np\n"
         "from marswalk.ml.thermal_emulator import build_dataset, train_mlp, evaluate\n"
         "\n"
         "Xtr, Ytr = build_dataset(4000, seed=0)\n"
         "Xte, Yte = build_dataset(1000, seed=99)\n"
         "t0 = time.time()\n"
         "model = train_mlp(Xtr, Ytr, epochs=200, device=dev)\n"
         "rep = evaluate(model, Xte, Yte)\n"
         "secs = time.time() - t0\n"
         "print(rep)"),
    code("report = {**rep.as_dict(), 'device': (torch.cuda.get_device_name(0) if dev=='cuda' else 'CPU'),\n"
         "          'epochs': 200, 'seconds': round(secs, 1), 'final_loss': round(model.history[-1], 6)}\n"
         "with open('thermal_emulator_report.json', 'w') as f:\n"
         "    json.dump(report, f, indent=2)\n"
         "print(json.dumps(report, indent=2))"),
    code("import matplotlib\n"
         "matplotlib.use('Agg')\n"
         "import matplotlib.pyplot as plt\n"
         "pred = model.predict(Xte)\n"
         "fig, ax = plt.subplots(1, 2, figsize=(11, 4.4))\n"
         "for j, name in enumerate(['T_min', 'T_max']):\n"
         "    ax[j].scatter(Yte[:, j], pred[:, j], s=5, alpha=.3, color='#e2572b')\n"
         "    lo, hi = Yte[:, j].min(), Yte[:, j].max()\n"
         "    ax[j].plot([lo, hi], [lo, hi], 'k--', lw=1)\n"
         "    ax[j].set_xlabel(f'physics {name} (K)'); ax[j].set_ylabel(f'emulated {name} (K)')\n"
         "    ax[j].set_title(name)\n"
         "fig.suptitle(f\"thermal emulator — MAE T_max {rep.mae_tmax_k:.2f} K, T_min {rep.mae_tmin_k:.2f} K\")\n"
         "fig.tight_layout(); fig.savefig('thermal_emulator_samples.png', dpi=120)\n"
         "print('wrote thermal_emulator_samples.png')"),
    md("## Send back\n\n"
       "Download **`thermal_emulator_report.json`** and **`thermal_emulator_samples.png`** "
       "and send them to the lead. Thanks!"),
])


if __name__ == "__main__":
    NB.mkdir(exist_ok=True)
    write(NB / "train_planner_heuristic.ipynb", HEURISTIC)
    write(NB / "train_dtm_artifacts.ipynb", DTM_ARTIFACTS)
    write(NB / "train_thermal_emulator.ipynb", THERMAL)
