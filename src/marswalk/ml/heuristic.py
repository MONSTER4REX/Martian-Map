"""M7 (optional): a learned A* heuristic — predict on-foot cost-to-go to a goal.

This is the self-contained ML model of the roadmap: its training data is
generated by the project's **own** planner (no external dataset), so a friend can
verify it end-to-end in minutes on any GPU (or CPU). For many random terrains and
goals we compute the *true* minimum on-foot time from every cell to the goal with
``walkback.time_to_haven_field`` (an exact Dijkstra), then fit a small MLP to
predict it from cheap per-cell features.

A heuristic is useful to A* only if it is close to the true cost **and rarely
overestimates** (overestimates break admissibility / optimality). So we report
both error (MAE/RMSE, vs the trivial straight-line lower bound) and the
**admissible fraction** = share of cells where prediction <= truth. Nothing here
is fabricated: every target is an exact planner computation.
"""

from __future__ import annotations

from dataclasses import dataclass, field

import numpy as np

from marswalk.physics.locomotion import LocomotionParams
from marswalk.physics.walkback import time_to_haven_field
from marswalk.planner.grid import Cell, Grid
from marswalk.terrain.synthetic import random_smooth_terrain

FEATURE_NAMES = ("horiz_dist_m", "dz_to_goal_m", "abs_dz_m", "flat_time_s")


def _flat_speed(loco: LocomotionParams | None = None) -> float:
    """Level-ground walking speed (m/s) implied by the locomotion model."""
    loco = loco or LocomotionParams()
    from marswalk.physics.locomotion import edge_time_s

    return 1.0 / edge_time_s(0.0, 1.0, loco)  # time for 1 m flat -> speed


def cell_features(grid: Grid, goal: Cell, loco: LocomotionParams | None = None):
    """Per-known-cell features and the straight-line lower-bound time.

    Returns ``(X, coords, flat_time)`` where ``X`` is (N, 4), ``coords`` the list
    of (row, col), and ``flat_time`` the trivial admissible lower bound (s).
    """
    loco = loco or LocomotionParams()
    speed = _flat_speed(loco)
    cs = grid.cellsize
    elev = grid.elevation
    zg = float(elev[goal])
    gr, gc = goal
    rows, cols = np.where(np.isfinite(elev))
    horiz = np.hypot((rows - gr) * cs, (cols - gc) * cs)
    dz = zg - elev[rows, cols]
    flat_time = horiz / speed
    X = np.column_stack([horiz, dz, np.abs(dz), flat_time]).astype(np.float32)
    coords = list(zip(rows.tolist(), cols.tolist(), strict=True))
    return X, coords, flat_time.astype(np.float32)


def build_dataset(
    seeds,
    shape: tuple[int, int] = (40, 40),
    cellsize: float = 10.0,
    relief_m: float = 40.0,
    passes: int = 8,
    loco: LocomotionParams | None = None,
):
    """Assemble (features, true cost-to-go) over many random terrains/goals.

    One random goal per terrain; targets are the exact on-foot time to that goal
    (``time_to_haven_field`` with the goal as the only haven). Unreachable cells
    are dropped. Returns ``(X, y, flat)`` float32 arrays.
    """
    loco = loco or LocomotionParams()
    Xs, ys, flats = [], [], []
    rng = np.random.default_rng(0)
    for s in seeds:
        grid = random_smooth_terrain(*shape, cellsize=cellsize, seed=int(s),
                                     relief_m=relief_m, passes=passes)
        goal = (int(rng.integers(shape[0])), int(rng.integers(shape[1])))
        truth = time_to_haven_field(grid, [goal], loco=loco)
        X, coords, flat = cell_features(grid, goal, loco)
        t = np.array([truth[r, c] for r, c in coords], dtype=np.float32)
        ok = np.isfinite(t)
        Xs.append(X[ok]); ys.append(t[ok]); flats.append(flat[ok])
    return np.concatenate(Xs), np.concatenate(ys), np.concatenate(flats)


@dataclass
class HeuristicModel:
    """A trained heuristic: standardizer + MLP weights (framework-agnostic eval)."""

    mean: np.ndarray
    std: np.ndarray
    y_mean: float = 0.0
    y_std: float = 1.0
    state: object = None          # torch state_dict (if torch available)
    history: list[float] = field(default_factory=list)
    _net: object = None

    def predict(self, X: np.ndarray) -> np.ndarray:
        import torch

        Xn = (X - self.mean) / self.std
        with torch.no_grad():
            out = self._net(torch.from_numpy(Xn.astype(np.float32)))
        return (out.squeeze(-1).cpu().numpy() * self.y_std + self.y_mean)


def _make_net():
    import torch.nn as nn

    return nn.Sequential(
        nn.Linear(4, 64), nn.ReLU(),
        nn.Linear(64, 64), nn.ReLU(),
        nn.Linear(64, 1),
    )


def train_mlp(X, y, epochs: int = 60, lr: float = 1e-3, device: str = "cpu",
              batch: int = 4096, seed: int = 0) -> HeuristicModel:
    """Fit the MLP (MSE on standardized features). Small enough for CPU or any GPU."""
    import torch

    torch.manual_seed(seed)
    mean = X.mean(axis=0); std = X.std(axis=0) + 1e-6
    y_mean = float(y.mean()); y_std = float(y.std()) + 1e-6
    Xn = ((X - mean) / std).astype(np.float32)
    yn = ((y - y_mean) / y_std).astype(np.float32)   # standardize target too
    dev = torch.device(device if (device == "cpu" or torch.cuda.is_available()) else "cpu")
    net = _make_net().to(dev)
    opt = torch.optim.Adam(net.parameters(), lr=lr)
    lossf = torch.nn.MSELoss()
    Xt = torch.from_numpy(Xn).to(dev)
    yt = torch.from_numpy(yn).to(dev).unsqueeze(-1)
    n = Xt.shape[0]
    history: list[float] = []
    for _ in range(epochs):
        perm = torch.randperm(n, device=dev)
        tot = 0.0
        for i in range(0, n, batch):
            idx = perm[i:i + batch]
            opt.zero_grad()
            loss = lossf(net(Xt[idx]), yt[idx])
            loss.backward(); opt.step()
            tot += loss.item() * len(idx)
        history.append(tot / n)
    net.eval()
    m = HeuristicModel(mean=mean, std=std, y_mean=y_mean, y_std=y_std,
                       state=net.state_dict(), history=history)
    m._net = net.cpu()
    return m


@dataclass
class HeuristicReport:
    n: int
    mae_s: float
    rmse_s: float
    admissible_fraction: float          # share with pred <= truth (A*-safe)
    baseline_mae_s: float               # straight-line lower bound's MAE
    improvement_vs_baseline: float      # 1 - mae/baseline_mae

    def as_dict(self) -> dict:
        return {
            "n": self.n, "mae_s": self.mae_s, "rmse_s": self.rmse_s,
            "admissible_fraction": self.admissible_fraction,
            "baseline_mae_s": self.baseline_mae_s,
            "improvement_vs_baseline": self.improvement_vs_baseline,
        }


def evaluate(model: HeuristicModel, X, y, flat) -> HeuristicReport:
    """Error + admissibility vs the trivial straight-line lower bound."""
    pred = model.predict(X)
    err = pred - y
    mae = float(np.mean(np.abs(err)))
    rmse = float(np.sqrt(np.mean(err ** 2)))
    adm = float(np.mean(pred <= y + 1e-6))
    base_mae = float(np.mean(np.abs(flat - y)))
    return HeuristicReport(
        n=int(len(y)), mae_s=mae, rmse_s=rmse, admissible_fraction=adm,
        baseline_mae_s=base_mae,
        improvement_vs_baseline=(1.0 - mae / base_mae) if base_mae else 0.0,
    )
