"""C2 DEM error model: spatially-correlated noise ensembles.

A DEM has correlated, not white, error. We perturb the DEM with Gaussian random
fields whose variance (sill), correlation length (range) and nugget come from a
variogram an owner fits to real residuals (e.g. controlled-vs-uncontrolled
offsets, overlap differences). The ensemble feeds route-stability (P6): how
often the recommended route changes under DEM perturbation.

Offline, the correlated field is generated by FFT-convolving white noise with a
Gaussian kernel (so the induced covariance is approximately Gaussian, not a
pure exponential variogram — documented, and good enough for perturbation
ensembles). Units: elevation and sill in m^2 (sill/nugget are variances),
range_m in meters. NaN cells stay NaN.
"""

from __future__ import annotations

import numpy as np
from pydantic import BaseModel, Field

from marswalk.planner.grid import Grid


class DEMErrorModel(BaseModel):
    sill_m2: float = Field(gt=0)  # correlated variance (m^2)
    range_m: float = Field(gt=0)  # correlation length (m)
    nugget_m2: float = Field(default=0.0, ge=0)  # white variance (m^2)


def _gaussian_field(
    shape: tuple[int, int], sigma_cells: float, rng: np.random.Generator
) -> np.ndarray:
    """Unit-variance, zero-mean Gaussian random field with correlation length
    ~ sigma_cells (FFT convolution of white noise with a Gaussian kernel)."""
    white = rng.standard_normal(shape)
    ny, nx = shape
    fy = np.fft.fftfreq(ny)[:, None]
    fx = np.fft.fftfreq(nx)[None, :]
    transfer = np.exp(-2.0 * (np.pi**2) * (sigma_cells**2) * (fx**2 + fy**2))
    field = np.fft.ifft2(np.fft.fft2(white) * transfer).real
    std = field.std()
    if std > 0:
        field = (field - field.mean()) / std
    return field


def sample_error(
    grid: Grid, model: DEMErrorModel, rng: np.random.Generator
) -> np.ndarray:
    """One correlated error realization (m), shape of the grid. NaN where nodata."""
    sigma_cells = max(model.range_m / grid.cellsize, 1e-6)
    field = _gaussian_field(grid.shape, sigma_cells, rng)
    err = np.sqrt(model.sill_m2) * field
    if model.nugget_m2 > 0:
        err = err + np.sqrt(model.nugget_m2) * rng.standard_normal(grid.shape)
    err[~np.isfinite(grid.elevation)] = np.nan
    return err


def perturbed_grid(grid: Grid, model: DEMErrorModel, rng: np.random.Generator) -> Grid:
    """A DEM realization = elevation + one correlated error field."""
    return Grid(grid.elevation + sample_error(grid, model, rng), grid.cellsize)


def ensemble(grid: Grid, model: DEMErrorModel, n: int, seed: int = 0) -> list[Grid]:
    """`n` perturbed DEM realizations (reproducible from `seed`)."""
    rng = np.random.default_rng(seed)
    return [perturbed_grid(grid, model, rng) for _ in range(n)]


def empirical_variogram(
    grid: Grid, n_lags: int = 10, max_lag_cells: int | None = None
) -> tuple[np.ndarray, np.ndarray]:
    """Isotropic empirical semivariogram via axis shifts. Returns (lags_m, gamma).

    gamma(h) = 0.5 * mean((z_i - z_{i+h})^2) over row- and col-shifted pairs,
    NaN pairs ignored.
    """
    z = grid.elevation
    max_lag = max_lag_cells or max(2, min(grid.nrows, grid.ncols) // 3)
    lags = np.arange(1, max_lag + 1)
    gamma = np.empty(len(lags), dtype=float)
    for i, k in enumerate(lags):
        diffs = []
        if grid.nrows > k:
            d = z[k:, :] - z[:-k, :]
            diffs.append(d[np.isfinite(d)])
        if grid.ncols > k:
            d = z[:, k:] - z[:, :-k]
            diffs.append(d[np.isfinite(d)])
        alld = np.concatenate(diffs) if diffs else np.array([])
        gamma[i] = 0.5 * float(np.mean(alld**2)) if alld.size else np.nan
    return lags * grid.cellsize, gamma


def fit_exponential_variogram(
    lags_m: np.ndarray, gamma: np.ndarray
) -> DEMErrorModel:
    """Least-squares fit of gamma(h) = nugget + sill*(1 - exp(-h/range)).

    Grid-searches `range` and solves the (nugget, sill) linear subproblem for
    each, keeping the best non-negative fit. No scipy dependency.
    """
    mask = np.isfinite(gamma)
    h = np.asarray(lags_m)[mask]
    y = np.asarray(gamma)[mask]
    if h.size < 2:
        raise ValueError("need at least 2 finite variogram points to fit")

    best = None
    for rng_m in np.linspace(h.min() / 2, h.max() * 2, 60):
        basis = 1.0 - np.exp(-h / rng_m)
        # y ~ nugget*1 + sill*basis  (non-negative LS via clipped normal eqns)
        A = np.column_stack([np.ones_like(h), basis])
        coef, *_ = np.linalg.lstsq(A, y, rcond=None)
        nugget, sill = max(coef[0], 0.0), max(coef[1], 1e-9)
        resid = float(np.mean((nugget + sill * basis - y) ** 2))
        if best is None or resid < best[0]:
            best = (resid, sill, rng_m, nugget)
    _, sill, rng_m, nugget = best  # type: ignore[misc]
    return DEMErrorModel(sill_m2=sill, range_m=float(rng_m), nugget_m2=nugget)
